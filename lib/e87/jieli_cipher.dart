List<int> _condMix(List<int> state, List<int> keyBlock, int mask, int phase) {
  final result = List<int>.from(state);
  for (var i = 0; i < 16; i++) {
    final bitSet = ((1 << i) & mask) != 0;
    if (phase == 3) {
      result[i] = bitSet ? (result[i] ^ keyBlock[i]) : ((keyBlock[i] + result[i]) & 0xFF);
    } else {
      result[i] = bitSet ? ((keyBlock[i] + result[i]) & 0xFF) : (result[i] ^ keyBlock[i]);
    }
  }
  return result;
}

List<int> _sboxSub(List<int> state) {
  final result = List<int>.from(state);
  for (final pos in const [0, 3, 4, 7, 8, 11, 12, 15]) {
    result[pos] = _sbox[result[pos]];
  }
  for (final pos in const [1, 2, 5, 6, 9, 10, 13, 14]) {
    result[pos] = _isbox[result[pos]];
  }
  return result;
}

void _blockCipher(List<int> state, List<int> ek, int mode) {
  var s = List<int>.from(state);
  final initial = List<int>.from(state);

  s = _condMix(s, ek.sublist(0, 16), _mask, 3);
  s = _sboxSub(s);
  s = _condMix(s, ek.sublist(16, 32), _mask, 5);

  for (var x9 = 1; x9 <= 8; x9++) {
    s = _fibonacciMix(s);
    final ekOff = x9 * 0x20;

    if (x9 == 8) {
      s = _condMix(s, ek.sublist(0x100, 0x110), _mask, 3);
      break;
    }

    if (mode != 0 && x9 == 2) {
      for (var i = 0; i < 16; i++) {
        final bitSet = ((1 << i) & _mask) != 0;
        s[i] = bitSet ? (s[i] ^ initial[i]) : ((initial[i] + s[i]) & 0xFF);
      }
    }

    s = _condMix(s, ek.sublist(ekOff, ekOff + 16), _mask, 3);
    s = _sboxSub(s);
    s = _condMix(s, ek.sublist(ekOff + 16, ekOff + 32), _mask, 5);
  }

  for (var i = 0; i < 16; i++) {
    state[i] = s[i];
  }
}

List<int> _functionE1test(List<int> key6, List<int> input16, List<int> seed16) {
  final expandedKey = List<int>.generate(16, (i) => key6[i % 6]);
  final output = List<int>.from(input16.sublist(0, 16));
  final ks = _keySchedule(List<int>.from(seed16.sublist(0, 16)));
  _blockCipher(output, ks, 0);

  for (var i = 0; i < 16; i++) {
    output[i] = (expandedKey[i] + (output[i] ^ input16[i])) & 0xFF;
  }

  final obf = List<int>.filled(16, 0);
  obf[0] = (seed16[0] - 0x17) & 0xFF;
  obf[1] = (seed16[1] ^ 0xE5) & 0xFF;
  obf[2] = (seed16[2] - 0x21) & 0xFF;
  obf[3] = (seed16[3] ^ 0xC1) & 0xFF;
  obf[4] = (seed16[4] - 0x4D) & 0xFF;
  obf[5] = (seed16[5] ^ 0xA7) & 0xFF;
  obf[6] = (seed16[6] - 0x6B) & 0xFF;
  obf[7] = (seed16[7] ^ 0x83) & 0xFF;
  obf[8] = (seed16[8] ^ 0xE9) & 0xFF;
  obf[9] = (seed16[9] - 0x1B) & 0xFF;
  obf[10] = (seed16[10] ^ 0xDF) & 0xFF;
  obf[11] = (seed16[11] - 0x3F) & 0xFF;
  obf[12] = (seed16[12] ^ 0xB3) & 0xFF;
  obf[13] = (seed16[13] - 0x59) & 0xFF;
  obf[14] = (seed16[14] ^ 0x95) & 0xFF;
  obf[15] = (seed16[15] - 0x7D) & 0xFF;

  final ks2 = _keySchedule(obf);
  _blockCipher(output, ks2, 1);
  return output;
}

/// Fresh 16-byte random challenge (no protocol prefix byte).
Uint8List getRandomAuthData() {
  final rng = Random.secure();
  return Uint8List.fromList(List<int>.generate(16, (_) => rng.nextInt(256)));
}

/// Compute the 16-byte auth response for a 16-byte challenge.
///
/// Both [challenge] and the return value are the raw payloads — the wire
/// prefix byte (0x00 / 0x01) is NOT included.
Uint8List getEncryptedAuthData(List<int> challenge) {
  final input = List<int>.from(challenge.sublist(0, 16));
  final encrypted = _functionE1test(_magic, input, List<int>.from(_staticKey));
  return Uint8List.fromList(encrypted);
}
