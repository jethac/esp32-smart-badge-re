List<int> _keySchedule(List<int> data16) {
  final out = List<int>.filled(272, 0);
  for (var i = 0; i < 16; i++) {
    out[i] = data16[i];
  }
  final buf = List<int>.from(data16.sublist(0, 16));
  var checksum = 0;
  for (final b in data16) {
    checksum ^= b;
  }
  buf.add(checksum & 0xFF);

  for (var rnd = 0; rnd < 16; rnd++) {
    for (var i = 0; i < 17; i++) {
      final b = buf[i];
      buf[i] = ((b << 3) | (b >> 5)) & 0xFF;
    }
    var readPos = (rnd + 1) % 17;
    for (var j = 0; j < 16; j++) {
      final src = buf[readPos];
      final tblIdx = 0xF + rnd * 16 - j;
      out[16 + rnd * 16 + j] = (_ksTable[tblIdx] + src) & 0xFF;
      readPos += 1;
      if (readPos > 16) readPos = 0;
    }
  }
  return out;
}

